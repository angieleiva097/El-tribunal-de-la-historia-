function crearElemento(etiqueta, clase = "", texto = "") {
  const elemento = document.createElement(etiqueta);
  if (clase) elemento.className = clase;
  if (texto !== "") elemento.textContent = texto;
  return elemento;
}

function reproducirEfecto(tipo) {
  document.dispatchEvent(
    new CustomEvent("efectoTribunal", {
      detail: { tipo }
    })
  );
}

function crearPortada(nombre, subtitulo, descripcion, icono) {
  const portada = crearElemento("section", "portada-archivo");

  portada.append(
    crearElemento("div", "sello", icono),
    crearElemento("h1", "", nombre),
    crearElemento("h2", "", subtitulo),
    crearElemento("p", "", descripcion)
  );

  return portada;
}

function crearEnlace(texto, url) {
  if (!url) {
    return crearElemento(
      "p",
      "nota-fuente",
      "Fuente documental pendiente de incorporar."
    );
  }

  const enlace = crearElemento("a", "enlace-documento", texto);
  enlace.href = url;
  enlace.target = "_blank";
  enlace.rel = "noopener noreferrer";

  return enlace;
}

function abrirHojas(titulo, hojas, enlaceDocumento = "") {
  reproducirEfecto("expediente");

  const anteriorVisor = contenedor.querySelector(".visor-documento");
  if (anteriorVisor) anteriorVisor.remove();

  const visor = crearElemento("section", "visor-documento");
  const papel = crearElemento("article", "hoja-expediente");
  const controles = crearElemento("div", "controles-paginas");

  const anterior = crearElemento("button", "boton-archivo", "← Anterior");
  const siguiente = crearElemento("button", "boton-archivo", "Siguiente →");
  const contador = crearElemento("span", "contador-paginas");
  const imprimir = crearElemento(
    "button",
    "boton-archivo",
    "🖨 Imprimir / Guardar PDF"
  );

  anterior.type = "button";
  siguiente.type = "button";
  imprimir.type = "button";

  let pagina = 0;

  function mostrarHoja() {
    papel.replaceChildren();

    const tituloHoja = crearElemento("h2", "", titulo);
    const contenidoHoja = crearElemento("p", "", hojas[pagina]);

    contenidoHoja.style.whiteSpace = "pre-line";
    contenidoHoja.style.lineHeight = "1.8";

    papel.append(tituloHoja, contenidoHoja);

    papel.appendChild(
      crearElemento(
        "p",
        "nota-fuente",
        `Folio ${pagina + 1} de ${hojas.length}`
      )
    );

    if (enlaceDocumento && pagina === hojas.length - 1) {
      papel.appendChild(
        crearEnlace("📄 Consultar fuente histórica", enlaceDocumento)
      );
    }

    contador.textContent = `Página ${pagina + 1} de ${hojas.length}`;
    anterior.disabled = pagina === 0;
    siguiente.disabled = pagina === hojas.length - 1;
  }

  anterior.addEventListener("click", () => {
    if (pagina > 0) {
      pagina--;
      mostrarHoja();
      reproducirEfecto("pagina");
    }
  });

  siguiente.addEventListener("click", () => {
    if (pagina < hojas.length - 1) {
      pagina++;
      mostrarHoja();
      reproducirEfecto("pagina");
    }
  });

  imprimir.addEventListener("click", () => {
    const ventana = window.open("", "_blank");

    if (!ventana) {
      alert("Permite las ventanas emergentes para guardar el documento.");
      return;
    }

    const documento = ventana.document;
    documento.title = titulo;

    const estilo = documento.createElement("style");
    estilo.textContent = `
      body {
        font-family: Georgia, serif;
        color: #282018;
        padding: 35px;
        line-height: 1.8;
      }
      article {
        break-after: page;
        margin-bottom: 35px;
      }
      p {
        white-space: pre-line;
      }
      h1, h2 {
        color: #633d23;
      }
    `;

    documento.head.appendChild(estilo);

    documento.body.appendChild(
      crearTextoImpresion(documento, "h1", titulo)
    );

    hojas.forEach((contenido, indice) => {
      const articulo = documento.createElement("article");

      articulo.append(
        crearTextoImpresion(documento, "h2", `Folio ${indice + 1}`),
        crearTextoImpresion(documento, "p", contenido)
      );

      documento.body.appendChild(articulo);
    });

    ventana.focus();
    ventana.print();
  });

  controles.append(anterior, contador, siguiente, imprimir);
  visor.append(papel, controles);
  contenedor.appendChild(visor);

  mostrarHoja();

  visor.scrollIntoView({
    behavior: "smooth",
    block: "start"
  });
}

function crearTextoImpresion(documento, etiqueta, texto) {
  const elemento = documento.createElement(etiqueta);
  elemento.textContent = texto;
  return elemento;
}

function crearCarpeta(titulo, indice, accion, tipo = "carpeta") {
  const boton = crearElemento("button", tipo);
  boton.type = "button";

  const simbolo = crearElemento(
    "span",
    "simbolo",
    tipo.includes("libro") ? "📖" : "📁"
  );

  const nombre = crearElemento("strong", "", titulo);
  const indicacion = crearElemento("small", "", "Haz clic para abrir");

  boton.append(simbolo, nombre, indicacion);
  boton.addEventListener("click", accion);

  return boton;
}

